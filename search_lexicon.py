class SmartLawSearch:
    """Умный локальный поиск по laws.db без внешних API и без изменения БД."""

    WORD_RE = re.compile(r"[а-яa-z0-9]+(?:\.[0-9]+)*", re.IGNORECASE)

    def __init__(self, database):
        self.database = database
        self._group_variants = {
            canonical: {self._normalize_phrase(v) for v in variants} | {self._normalize_phrase(canonical)}
            for canonical, variants in SearchLexicon.KEYWORD_GROUPS.items()
        }
        self._triggers = {
            canonical: {self._normalize_phrase(v) for v in phrases}
            for canonical, phrases in SearchLexicon.TRIGGER_PHRASES.items()
        }
        self._law_aliases = {
            canonical: {self._normalize_phrase(v) for v in aliases} | {self._normalize_phrase(canonical)}
            for canonical, aliases in SearchLexicon.LAW_ALIASES.items()
        }

    @staticmethod
    def _normalize_phrase(text):
        value = (text or "").lower().replace("ё", "е")
        value = value.replace("—", " ").replace("–", " ").replace("-", " ")
        value = re.sub(r"[^а-яa-z0-9.]+", " ", value)
        return re.sub(r"\s+", " ", value).strip()

    def normalize_query(self, query):
        value = self._normalize_phrase(query)

        for wrong, right in SearchLexicon.TYPO_REPLACEMENTS.items():
            value = value.replace(self._normalize_phrase(wrong), self._normalize_phrase(right))

        # Удаляем длинные фразы-паразиты раньше отдельных слов.
        padded = f" {value} "
        for phrase in sorted(SearchLexicon.FILLER_PHRASES, key=len, reverse=True):
            normalized_phrase = self._normalize_phrase(phrase)
            padded = padded.replace(f" {normalized_phrase} ", " ")
        return re.sub(r"\s+", " ", padded).strip()

    def _tokens(self, text):
        return self.WORD_RE.findall(self._normalize_phrase(text))

    def _query_profile(self, query):
        normalized = self.normalize_query(query)
        all_tokens = self._tokens(normalized)
        useful_tokens = [
            token for token in all_tokens
            if (len(token) >= 2 or token.isdigit()) and token not in SearchLexicon.STOP_WORDS
        ]

        weighted_terms = defaultdict(float)
        for token in useful_tokens:
            weighted_terms[token] = max(weighted_terms[token], 1.0)

        matched_groups = []
        matched_phrases = []

        # Сильные фразовые триггеры.
        padded = f" {normalized} "
        for canonical, phrases in self._triggers.items():
            if any(f" {phrase} " in padded for phrase in phrases):
                matched_phrases.append(canonical)
                weighted_terms[canonical] = max(weighted_terms[canonical], 2.2)

        # Синонимы и разговорные варианты.
        for canonical, variants in self._group_variants.items():
            hit = False
            for variant in variants:
                if " " in variant:
                    if f" {variant} " in padded:
                        hit = True
                        break
                elif variant in useful_tokens:
                    hit = True
                    break
            if not hit:
                continue

            matched_groups.append(canonical)
            weighted_terms[canonical] = max(weighted_terms[canonical], 1.7)
            # Расширяем запрос вариантами, но с меньшим весом, чтобы не размыть исходный смысл.
            for variant in variants:
                if " " not in variant and len(variant) >= 3:
                    weighted_terms[variant] = max(weighted_terms[variant], 0.45)

        requested_laws = []
        for canonical, aliases in self._law_aliases.items():
            for alias in aliases:
                if (" " in alias and f" {alias} " in padded) or (" " not in alias and alias in all_tokens):
                    requested_laws.append(canonical)
                    break

        return {
            "normalized": normalized,
            "original_terms": set(useful_tokens),
            "weighted_terms": dict(weighted_terms),
            "matched_groups": matched_groups,
            "matched_phrases": matched_phrases,
            "requested_laws": requested_laws,
        }

    @staticmethod
    def _starts_with_stem(words, term):
        if len(term) < 5:
            return False
        # Небольшой префиксный stem хорошо работает для русских падежей/окончаний
        # и не требует pymorphy2/nltk.
        stem_len = 5 if len(term) <= 8 else 6
        stem = term[:stem_len]
        return any(word.startswith(stem) for word in words)

    def _law_alias_match(self, law_title, requested_law):
        title = self._normalize_phrase(law_title)
        aliases = self._law_aliases.get(requested_law, {requested_law})
        return any(alias in title for alias in aliases)

    @staticmethod
    def _law_short_name(title):
        value = (title or "").lower().replace("ё", "е")
        if "коап" in value or "административ" in value:
            return "КоАП"
        if re.search(r"(^|\s)ук(\s|$)", value) or "уголовный кодекс" in value:
            return "УК РФ"
        if "пдд" in value or "правила дорожного движения" in value:
            return "ПДД"
        if "упк" in value or "уголовно-процесс" in value or "уголовно процесс" in value:
            return "УПК"
        if "конституц" in value:
            return "Конституция"
        return (title or "").strip()

    def _suggest_match_score(self, query, candidate):
        q = self._normalize_phrase(query)
        c = self._normalize_phrase(candidate)
        if not q or not c:
            return 0

        if c == q:
            return 120
        if c.startswith(q):
            return 100 - min(len(c) - len(q), 30) * 0.15
        if len(q) >= 4 and q in c:
            return 82 - min(c.index(q), 20) * 0.25

        q_tokens = [
            t for t in self._tokens(q)
            if t not in SearchLexicon.STOP_WORDS
        ]
        c_tokens = self._tokens(c)
        if not q_tokens or not c_tokens:
            return 0

        matched = 0
        for token in q_tokens:
            if any(word.startswith(token) for word in c_tokens):
                matched += 1
        if matched == len(q_tokens):
            return 66 + matched * 3
        if matched and matched / len(q_tokens) >= 0.6:
            return 40 + matched * 3
        return 0

    def suggest(self, query, limit=10, history=None):
        """Возвращает живые варианты поискового запроса.

        Подсказки строятся из локального словаря, истории пользователя и реально
        загруженной базы законов: прошлые запросы, синонимы, юридические триггеры,
        названия документов и реальные статьи.
        """
        raw = (query or "").strip()
        if len(raw) < 2:
            return []

        normalized = self.normalize_query(raw)
        if not normalized:
            normalized = self._normalize_phrase(raw)

        ranked = {}

        def add(text, score):
            text = re.sub(r"\s+", " ", str(text or "")).strip()
            if not text or score <= 0:
                return
            key = self._normalize_phrase(text)
            if not key:
                return
            current = ranked.get(key)
            if current is None or score > current[0]:
                ranked[key] = (float(score), text)

        # Недавние успешные запросы пользователя получают высокий приоритет.
        # Благодаря этому подсказки постепенно становятся персональнее, но
        # фактические результаты всё равно берутся только из laws.db.
        for position, previous in enumerate(history or []):
            previous = str(previous or "").strip()
            score = self._suggest_match_score(normalized, previous)
            if score > 0:
                add(previous, score + max(6, 26 - position * 1.5))

        # Темы, синонимы и разговорные формулировки.
        for canonical, variants in SearchLexicon.KEYWORD_GROUPS.items():
            phrases = [canonical] + sorted(variants, key=lambda x: (len(x), x))
            direct_scores = [self._suggest_match_score(normalized, phrase) for phrase in phrases]
            best = max(direct_scores, default=0)
            if best <= 0:
                continue
            add(canonical, best + 18)
            # После совпадения с одним синонимом предлагаем несколько близких вариантов.
            related = sorted(
                ((self._suggest_match_score(normalized, p), p) for p in phrases),
                key=lambda item: (item[0], -len(item[1])),
                reverse=True,
            )
            used = 0
            for score, phrase in related:
                if phrase == canonical:
                    continue
                add(phrase, (score if score > 0 else best * 0.55) + 5)
                used += 1
                if used >= 4:
                    break

        # Сильные юридические фразы.
        for canonical, phrases in SearchLexicon.TRIGGER_PHRASES.items():
            all_phrases = [canonical] + sorted(phrases, key=lambda x: (len(x), x))
            best = max((self._suggest_match_score(normalized, p) for p in all_phrases), default=0)
            if best <= 0:
                continue
            add(canonical, best + 24)
            for phrase in all_phrases:
                score = self._suggest_match_score(normalized, phrase)
                if score > 0:
                    add(phrase, score + 10)

        # Сокращения и названия законов.
        law_display = {
            "коап": "КоАП",
            "ук": "УК РФ",
            "пдд": "ПДД",
            "упк": "УПК",
            "фз полиция": "ФЗ «О полиции»",
            "конституция": "Конституция",
        }
        for canonical, aliases in SearchLexicon.LAW_ALIASES.items():
            phrases = [canonical] + list(aliases)
            best = max((self._suggest_match_score(normalized, p) for p in phrases), default=0)
            if best > 0:
                add(law_display.get(canonical, canonical), best + 14)

        # Если пользователь вводит номер статьи, предлагаем реальные номера из БД.
        # Также показываем статью при прямом совпадении с её заголовком.
        has_digit = any(ch.isdigit() for ch in normalized)
        query_tokens = [t for t in self._tokens(normalized) if t not in SearchLexicon.STOP_WORDS]
        scan_titles = len(normalized) >= 4 and not has_digit

        for law in self.database.get_laws():
            law_title = law["title"] or ""
            short = self._law_short_name(law_title)
            law_score = self._suggest_match_score(normalized, short)

            if not (has_digit or scan_titles or law_score > 0):
                continue

            for article in self.database.get_articles_by_law(law["id"]):
                number = str(article["article_number"] or "").strip()
                title = (article["title"] or "").strip()
                base = f"{number} {short}".strip()
                display = base + (f" — {title}" if title else "")

                score = self._suggest_match_score(normalized, base)
                if title:
                    score = max(score, self._suggest_match_score(normalized, title) - 3)

                # Для ввода только номера статьи приоритетно показываем номера с таким префиксом.
                number_query = re.sub(r"[^0-9.]", "", normalized)
                if has_digit and number_query and number.startswith(number_query):
                    score = max(score, 96 - min(len(number) - len(number_query), 20))

                # Если указан кодекс, усиливаем статьи именно этого документа.
                if law_score > 0 and score > 0:
                    score += 8

                if score > 0:
                    add(display, score + 12)

        ordered = sorted(
            ranked.values(),
            key=lambda item: (-item[0], len(item[1]), item[1].lower()),
        )
        return [text for _, text in ordered[:max(1, int(limit))]]

    @staticmethod
    def lexicon_stats():
        """Small metrics block used by the DeiLaw status page."""
        keyword_variants = sum(
            len(values) + 1
            for values in SearchLexicon.KEYWORD_GROUPS.values()
        )
        trigger_variants = sum(
            len(values)
            for values in SearchLexicon.TRIGGER_PHRASES.values()
        )
        law_aliases = sum(
            len(values)
            for values in SearchLexicon.LAW_ALIASES.values()
        )
        return {
            "stop_words": len(SearchLexicon.STOP_WORDS),
            "filler_phrases": len(SearchLexicon.FILLER_PHRASES),
            "keyword_groups": len(SearchLexicon.KEYWORD_GROUPS),
            "keyword_variants": keyword_variants,
            "trigger_groups": len(SearchLexicon.TRIGGER_PHRASES),
            "trigger_variants": trigger_variants,
            "law_aliases": law_aliases,
            "typos": len(SearchLexicon.TYPO_REPLACEMENTS),
        }

    def search(self, query, limit=100):
        profile = self._query_profile(query)
        if not profile["normalized"]:
            return []

        terms = profile["weighted_terms"]
        if not terms:
            return []

        results = []
        query_phrase = profile["normalized"]

        for law in self.database.get_laws():
            law_title = law["title"] or ""
            law_norm = self._normalize_phrase(law_title)
            law_words = set(self._tokens(law_title))

            law_boost = 0.0
            if profile["requested_laws"]:
                if any(self._law_alias_match(law_title, item) for item in profile["requested_laws"]):
                    law_boost = 8.0

            for article in self.database.get_articles_by_law(law["id"]):
                title = article["title"] or ""
                content = article["content"] or ""
                title_norm = self._normalize_phrase(title)
                content_norm = self._normalize_phrase(content)
                title_words = set(self._tokens(title))
                content_words = set(self._tokens(content))

                score = law_boost
                matched = []

                # Полная фраза пользователя — сильный сигнал.
                if len(query_phrase) >= 5:
                    if query_phrase in title_norm:
                        score += 24.0
                    elif query_phrase in content_norm:
                        score += 12.0

                # Канонические группы/триггеры как фразы.
                for canonical in profile["matched_phrases"]:
                    canonical_norm = self._normalize_phrase(canonical)
                    if canonical_norm in title_norm:
                        score += 12.0
                        matched.append(canonical)
                    elif canonical_norm in content_norm:
                        score += 6.0
                        matched.append(canonical)

                for term, weight in terms.items():
                    term_n = self._normalize_phrase(term)
                    if not term_n:
                        continue

                    # Для многословных канонических понятий ищем как фразу.
                    if " " in term_n:
                        if term_n in title_norm:
                            score += 9.0 * weight
                            matched.append(term)
                        elif term_n in content_norm:
                            score += 4.0 * weight
                            matched.append(term)
                        continue

                    if term_n in title_words:
                        score += 7.0 * weight
                        matched.append(term)
                    elif term_n in law_words:
                        score += 4.5 * weight
                        matched.append(term)
                    elif term_n in content_words:
                        score += 2.5 * weight
                        matched.append(term)
                    elif self._starts_with_stem(title_words, term_n):
                        score += 4.0 * weight
                        matched.append(term)
                    elif self._starts_with_stem(content_words, term_n):
                        score += 1.25 * weight
                        matched.append(term)

                matched = list(dict.fromkeys(matched))

                # Совпадение только по названию документа без смысловых слов недостаточно.
                semantic_matches = [m for m in matched if self._normalize_phrase(m) not in law_words]
                if score < 2.5 or (not matched and law_boost <= 0):
                    continue
                if law_boost > 0 and not semantic_matches and len(profile["original_terms"]) > 1:
                    # Запрос вроде "пдд парковка" должен иметь совпадение и по теме.
                    continue

                results.append({
                    "id": article["id"],
                    "article_number": article["article_number"],
                    "article_title": title,
                    "content": content,
                    "law_title": law_title,
                    "url": law["url"],
                    "search_score": round(score, 2),
                    "matched_terms": matched[:12],
                })

        results.sort(
            key=lambda item: (
                item.get("search_score", 0),
                len(item.get("matched_terms", [])),
            ),
            reverse=True,
        )

        if results:
            return results[:limit]

        # Последний безопасный fallback: старый literal LIKE-поиск по целой фразе.
        try:
            return list(self.database.search_articles(query, limit))
        except Exception:
            return []
