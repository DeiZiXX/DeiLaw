-- If the developer uses the legacy developer_reply field in Table Editor,
-- turn each new reply into a normal chat message automatically.
create or replace function public.deilaw_bug_report_reply_to_chat()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.developer_reply is distinct from old.developer_reply
       and nullif(trim(coalesce(new.developer_reply, '')), '') is not null
    then
        insert into public.bug_report_messages (
            report_id,
            sender,
            message
        )
        values (
            new.id,
            'developer',
            trim(new.developer_reply)
        );
    end if;

    return new;
end;
$$;

drop trigger if exists deilaw_bug_report_reply_to_chat_trigger
    on public.bug_reports;

create trigger deilaw_bug_report_reply_to_chat_trigger
after update of developer_reply on public.bug_reports
for each row
execute function public.deilaw_bug_report_reply_to_chat();

-- Status changes also appear as system events in the report conversation.
create or replace function public.deilaw_bug_report_status_to_chat()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    status_text text;
begin
    if new.status is distinct from old.status then
        status_text := case new.status
            when 'new' then 'Новый'
            when 'checking' then 'Проверяется'
            when 'fixed' then 'Исправлено'
            when 'closed' then 'Закрыт'
            else new.status
        end;

        insert into public.bug_report_messages (
            report_id,
            sender,
            message
        )
        values (
            new.id,
            'system',
            'Статус репорта изменён: ' || status_text
        );
    end if;

    return new;
end;
$$;

drop trigger if exists deilaw_bug_report_status_to_chat_trigger
    on public.bug_reports;

create trigger deilaw_bug_report_status_to_chat_trigger
after update of status on public.bug_reports
for each row
execute function public.deilaw_bug_report_status_to_chat();

