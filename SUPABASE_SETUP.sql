    to anon, authenticated;

-- Fill message ownership from its parent report. Users never need to send
-- installation_id or the secret hash in the message payload itself.
create or replace function public.deilaw_fill_bug_message_owner()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    parent_report public.bug_reports%rowtype;
begin
    select *
    into parent_report
    from public.bug_reports
    where id = new.report_id;

    if not found then
        raise exception 'Bug report not found';
    end if;

    new.installation_id := parent_report.installation_id;
    new.installation_secret_hash :=
        parent_report.installation_secret_hash;

    return new;
end;
$$;

drop trigger if exists deilaw_fill_bug_message_owner_trigger
    on public.bug_report_messages;

create trigger deilaw_fill_bug_message_owner_trigger
before insert on public.bug_report_messages
for each row
execute function public.deilaw_fill_bug_message_owner();

-- Every new chat message moves the report to the top of "My reports".
create or replace function public.deilaw_touch_bug_report_from_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.bug_reports
    set updated_at = now()
    where id = new.report_id;

    return new;
end;
$$;

