-- This replaces the missing historical admin/suggestions setup for isolated tests.

create table if not exists public.deilaw_admins (
    user_id uuid primary key references auth.users(id),
    display_name text,
    created_at timestamptz not null default now()
);
alter table public.deilaw_admins enable row level security;
revoke all on public.deilaw_admins from anon, authenticated;
grant select on public.deilaw_admins to authenticated;
create policy "deilaw_local_admin_self" on public.deilaw_admins
    for select to authenticated using (user_id = (select auth.uid()));

create or replace function public.deilaw_is_admin()
returns boolean language sql stable set search_path = '' as $$
    select exists (
        select 1 from public.deilaw_admins
        where user_id = (select auth.uid())
    );
$$;
revoke all on function public.deilaw_is_admin() from public, anon;
grant execute on function public.deilaw_is_admin() to authenticated;

alter table public.reviews
    add column if not exists developer_reply text;
alter table public.reviews
    add column if not exists developer_reply_at timestamptz;

create table if not exists public.suggestions (
    id uuid primary key default gen_random_uuid(),
    suggestion_number bigint generated by default as identity unique,
    installation_id text not null,
    installation_secret_hash text not null,
    author_name text not null,
    category text not null default 'Функционал',
    title text not null,
    suggestion_text text not null,
    app_version text not null default '',
    status text not null default 'new',
    developer_reply text,
    developer_reply_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
alter table public.suggestions enable row level security;
revoke all on public.suggestions from anon, authenticated;
grant select, insert, update on public.suggestions to authenticated;
grant usage, select on sequence public.suggestions_suggestion_number_seq to authenticated;

-- Minimal admin policies matching the names preserved by the hardening migration.
create policy "deilaw_admin_reviews_read" on public.reviews
    for select to authenticated using (public.deilaw_is_admin());
create policy "deilaw_admin_reviews_update" on public.reviews
    for update to authenticated using (public.deilaw_is_admin())
    with check (public.deilaw_is_admin());
create policy "deilaw_admin_bug_read" on public.bug_reports
    for select to authenticated using (public.deilaw_is_admin());
create policy "deilaw_admin_bug_update" on public.bug_reports
    for update to authenticated using (public.deilaw_is_admin())
    with check (public.deilaw_is_admin());
create policy "deilaw_admin_bug_messages_read" on public.bug_report_messages
    for select to authenticated using (public.deilaw_is_admin());
create policy "deilaw_admin_bug_messages_insert" on public.bug_report_messages
    for insert to authenticated with check (public.deilaw_is_admin());

